// add-security-headers — a Content-Security-Policy and a referrer policy on
// every page.
//
// The live site sends NO security headers at all: no CSP, no HSTS, no
// X-Frame-Options, no X-Content-Type-Options, no Referrer-Policy. That is not
// negligence so much as GitHub Pages — it serves static files and gives you no
// way to set response headers. What it cannot stop you doing is putting the two
// that work as <meta> into the document itself.
//
// ⚠ WHAT THIS CAN AND CANNOT DO, said plainly so nobody thinks the job is done:
//   * Content-Security-Policy  — works as a meta tag, and is the one that
//     matters most here. It is the difference between "an injected <script
//     src=evil.com> runs" and "it is refused by the browser".
//   * Referrer-Policy          — works as <meta name="referrer">.
//   * X-Frame-Options          — CANNOT be set by meta. `frame-ancestors` in a
//     meta CSP is explicitly IGNORED by browsers, so clickjacking cover needs a
//     real header and therefore a real host or a CDN in front of Pages.
//   * HSTS, X-Content-Type-Options — response headers only. Not fixable here.
//     GitHub's "Enforce HTTPS" setting is what supplies HSTS; it is currently
//     not being sent for the apex, which is worth turning on in repo settings.
//
// 'unsafe-inline' is in script-src and it is worth being honest about why: this
// codebase puts its logic in inline <script> blocks on nearly every page —
// theme-before-paint, the whole dashboard, the whole settings page. Removing it
// would mean hashing or noncing dozens of blocks, and a nonce cannot be
// generated by a static host. So this CSP does NOT stop injected inline script.
// What it does stop is the more common and more damaging case: script pulled
// from a domain we do not list, form posts to somewhere else, and the page
// being framed by a third party where a real header is available.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

const ROOT = "C:\\sctools\\scpush";

// Every origin the site actually uses, gathered by grepping the source rather
// than guessed — a CSP built from memory is a CSP that breaks something.
const SUPABASE = "https://sobxhcsgtimtiqtvqbag.supabase.co";

// ⚠ THE CUSTOM AUTH DOMAIN IS LISTED ALONGSIDE THE PROJECT HOST, NOT INSTEAD
// OF IT, AND THAT IS THE WHOLE POINT OF ADDING IT EARLY.
//
// Ahmed, 11 Aug 2026: Google's sign-in prompt reads "to continue to
// sobxhcsgtimtiqtvqbag.supabase.co", which does not look like Sahaba Club to
// somebody signing up. The fix is a custom domain — and the trap is that the
// project host is named in the CSP of every page. Point auth at a new host
// without listing it here and the browser blocks every auth call: the site
// fails closed, silently, for everyone at once.
//
// Listing both means there is no flag day. This can ship weeks before the
// domain exists (a CSP source that nothing connects to costs nothing), the
// switch itself becomes one line in `lib/supabase-client.js`, and if the
// domain is ever rolled back the old host is still allowed.
//
// ⚠ REMOVING THE SUPABASE.CO HOST LATER IS A SEPARATE, LATER DECISION. Storage
// URLs already written into `profiles.avatar_url` and `events.image_url` point
// at it, and those rows outlive any DNS change. `img-src` is `https:` so
// pictures are unaffected, but do not assume the same of anything else.
const AUTH_DOMAIN = "https://auth.sahabaclub.ai";
const CSP = [
  "default-src 'self'",
  // esm.sh serves the Supabase client; googletagmanager only after consent.
  `script-src 'self' 'unsafe-inline' https://esm.sh https://www.googletagmanager.com`,
  "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
  "font-src 'self' https://fonts.gstatic.com data:",
  // Avatars come from Supabase storage and from the three identity providers;
  // data: and blob: are used for the local resize before upload.
  "img-src 'self' data: blob: https: ",
  // Supabase REST/auth/realtime/storage, plus GA4's collect endpoint.
  `connect-src 'self' ${SUPABASE} wss://sobxhcsgtimtiqtvqbag.supabase.co ${AUTH_DOMAIN} wss://auth.sahabaclub.ai https://www.google-analytics.com https://region1.google-analytics.com https://esm.sh`,
  // The EduHackAI demo videos.
  "frame-src https://www.youtube.com https://www.youtube-nocookie.com",
  "media-src 'self' blob:",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  // Ignored in a meta tag, kept so that moving behind a real host or CDN
  // carries the intent across rather than starting again.
  "frame-ancestors 'none'",
  "upgrade-insecure-requests",
].join("; ");

const META = `<meta http-equiv="Content-Security-Policy" content="${CSP}">
<meta name="referrer" content="strict-origin-when-cross-origin">`;

const MARK = 'http-equiv="Content-Security-Policy"';

function pages(dir, out = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.name === ".git" || e.name === ".claude" || e.name === "node_modules") continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) pages(p, out);
    else if (e.name.endsWith(".html")) out.push(p);
  }
  return out;
}

let added = 0, already = 0, skipped = 0;
for (const path of pages(ROOT)) {
  const src = readFileSync(path, "utf8");
  if (src.includes(MARK)) { already++; continue; }

  // Insert immediately after <meta charset>, which every page in this repo has
  // as its first head element. A CSP has to appear before anything it governs.
  const m = /<meta charset="[^"]*">\r?\n/i.exec(src);
  if (!m) { console.log(`  SKIPPED (no charset meta): ${path.replace(ROOT + "\\", "")}`); skipped++; continue; }

  const eol = src.includes("\r\n") ? "\r\n" : "\n";
  const at = m.index + m[0].length;
  const out = src.slice(0, at) + META.replace(/\n/g, eol) + eol + src.slice(at);
  writeFileSync(path, out, "utf8");
  added++;
}
console.log(`\nCSP + referrer policy: ${added} page(s) updated, ${already} already had it, ${skipped} skipped.`);
