// Emit the podcast_episodes seed for migration 0045 FROM podcast-data.js.
//
// Why a generator and not fifteen typed INSERT lines: 0043 exists because four
// live views were retyped-from-memory rather than recorded, and the project's
// own rule out of that episode is that anything transcribed into a migration
// should be generated from its source. Half these rows are Arabic titles; a
// transcription slip in one of them would be invisible in review and would
// ship a wrong title to every member's Podcast page.
//
// Reads:  podcast-data.js  (the current source of truth)
// Writes: stdout — paste into the migration, or redirect to a file.
//
// Run:  node tools/generate-podcast-seed.mjs

import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(join(here, "..", "podcast-data.js"), "utf8");

// The file declares plain `var`s and nothing else, so evaluating it in a
// throwaway scope is both the simplest and the most faithful reader — it
// cannot disagree with what the browser loads, which a regex could.
const scope = {};
new Function(
  "scope",
  src + "\nscope.EPISODES = PODCAST_EPISODES; scope.TRAILER = PODCAST_TRAILER;"
)(scope);

const episodes = scope.EPISODES;
if (!Array.isArray(episodes) || episodes.length === 0) {
  console.error("podcast-data.js yielded no episodes — refusing to emit an empty seed");
  process.exit(1);
}

// Postgres string literal: double every single quote. The Arabic titles carry
// none today, but "today" is exactly the assumption that breaks later.
const q = (v) => (v === null || v === undefined || v === "" ? "null" : `'${String(v).replace(/'/g, "''")}'`);

const seen = new Set();
for (const e of episodes) {
  if (!e.id || !/^[A-Za-z0-9_-]{11}$/.test(e.id)) {
    console.error(`episode ${e.n}: implausible YouTube id ${JSON.stringify(e.id)} — refusing`);
    process.exit(1);
  }
  if (seen.has(e.id)) {
    console.error(`duplicate YouTube id ${e.id} — refusing`);
    process.exit(1);
  }
  seen.add(e.id);
}

const rows = episodes
  .map(
    (e) =>
      `  (${e.n}, ${q(e.id)}, ${q(e.lang)}, ${q(e.topic)}, ${q(e.ar)})`
  )
  .join(",\n");

process.stdout.write(`-- GENERATED by tools/generate-podcast-seed.mjs from podcast-data.js
-- ${episodes.length} episodes. Do not hand-edit: re-run the generator.
insert into public.podcast_episodes
  (episode_number, youtube_id, language, topic, title_ar, is_published, announced_at)
select v.n, v.yt, v.lang, v.topic, v.ar, true, now()
  from (values
${rows}
  ) as v (n, yt, lang, topic, ar)
on conflict (youtube_id) do nothing;
`);
